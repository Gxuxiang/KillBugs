void AKBEnemyDirector::ConsoleSetSwarmCount(const TArray<FString>& Args, UWorld* World)
{
	if (!World)
	{
		return;
	}

	const int32 Count = Args.Num() > 0 ? FCString::Atoi(*Args[0]) : 500;

	for (TActorIterator<AKBEnemyDirector> It(World); It; ++It)
	{
		It->SpawnSwarm(Count, FVector::ZeroVector, 3000.f);
		UE_LOG(LogKillBugs, Display, TEXT("Swarm set to %d"), It->GetEnemyCount());
		return;
	}

	UE_LOG(LogKillBugs, Warning, TEXT("No AKBEnemyDirector in this world"));
}

void AKBEnemyDirector::ConsoleKillEnemies(const TArray<FString>& Args, UWorld* World)
{
	if (!World)
	{
		return;
	}

	const int32 Count = Args.Num() > 0 ? FCString::Atoi(*Args[0]) : 50;

	for (TActorIterator<AKBEnemyDirector> It(World); It; ++It)
	{
		const int32 Before = It->GetEnemyCount();
		for (int32 Index = 0; Index < Count && It->GetEnemyCount() > 0; ++Index)
		{
			It->ApplyDamageToEnemy(FMath::RandHelper(It->GetEnemyCount()), 1.0e9f, nullptr);
		}
		UE_LOG(LogKillBugs, Display, TEXT("Killed %d of %d"), Before - It->GetEnemyCount(), Before);
		return;
	}

	UE_LOG(LogKillBugs, Warning, TEXT("No AKBEnemyDirector in this world"));
}

void AKBEnemyDirector::ConsoleCullSwarm(const TArray<FString>& Args, UWorld* World)
{
	if (!World)
	{
		return;
	}

	for (TActorIterator<AKBEnemyDirector> It(World); It; ++It)
	{
		const int32 Before = It->GetEnemyCount();
		It->CullAllRemaining();

		// "removed", not "killed": this path takes the bugs out of the array without a death going
		// through ApplyDamageToEnemy, and every machine reads a removal as a death - so the
		// splatter that follows is an artifact of the shortcut rather than a report of anything.
		UE_LOG(LogKillBugs, Display, TEXT("Swarm culled: %d bug(s) removed"), Before);
		return;
	}

	UE_LOG(LogKillBugs, Warning, TEXT("No AKBEnemyDirector in this world"));
}

