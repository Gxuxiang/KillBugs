int32 AKBEnemyDirector::FindNearestEnemy(const FVector& Origin, float MaxRange, FVector& OutLocation) const
{
	int32 BestIndex = INDEX_NONE;
	float BestDistanceSq = FMath::Square(MaxRange);

	for (int32 Index = 0; Index < Sim.Num(); ++Index)
	{
		const float DistanceSq = FVector::DistSquared2D(Sim[Index].Location, Origin);
		if (DistanceSq < BestDistanceSq)
		{
			BestDistanceSq = DistanceSq;
			BestIndex = Index;
		}
	}

	if (BestIndex != INDEX_NONE)
	{
		OutLocation = Sim[BestIndex].Location;
	}
	return BestIndex;
}

int32 AKBEnemyDirector::ApplyRadialDamage(const FVector& Centre, float Radius, float Damage, AKBPlayerState* Killer)
{
	if (!HasAuthority())
	{
		return 0;
	}

	// Collect first, then damage in descending index order: ApplyDamageToEnemy removes dead
	// entries, and removing a lower index would shift every index above it.
	TArray<int32> Hits;
	for (int32 Index = 0; Index < Sim.Num(); ++Index)
	{
		// Same rule as the line test: a burst catches a bug whose BODY is in range, not merely
		// one whose centre is. See ApplyDamageAlongSegment.
		const UKBEnemyArchetype* Archetype =
			Archetypes.IsValidIndex(Sim[Index].ArchetypeIndex) ? Archetypes[Sim[Index].ArchetypeIndex].Get() : nullptr;
		const float BodyRadius = Archetype ? Archetype->BodyRadius : 0.f;
		const float EffectiveRadius = Radius + BodyRadius;

		if (FVector::DistSquared2D(Sim[Index].Location, Centre) <= FMath::Square(EffectiveRadius))
		{
			Hits.Add(Index);
		}
	}

	int32 Kills = 0;
	for (int32 Hit = Hits.Num() - 1; Hit >= 0; --Hit)
	{
		Kills += ApplyDamageToEnemy(Hits[Hit], Damage, Killer) ? 1 : 0;
	}
	return Kills;
}

bool AKBEnemyDirector::ApplyDamageAlongSegment(const FVector& Start, const FVector& End, float Radius,
                                               float Damage, AKBPlayerState* Killer, FVector* OutHitLocation)
{
	if (!HasAuthority())
	{
		return false;
	}

	const FVector Segment = End - Start;
	const float SegmentLengthSq = Segment.SizeSquared();
	if (SegmentLengthSq <= KINDA_SMALL_NUMBER)
	{
		return false;
	}

	// Closest bug to the line, within Radius, and in front of the muzzle.
	int32 BestIndex = INDEX_NONE;
	float BestAlong = TNumericLimits<float>::Max();

	for (int32 Index = 0; Index < Sim.Num(); ++Index)
	{
		const FVector ToEnemy = Sim[Index].Location - Start;
		const float Along = FVector::DotProduct(ToEnemy, Segment) / SegmentLengthSq;
		if (Along < 0.f || Along > 1.f)
		{
			continue;
		}

		// The shot's radius PLUS the target's body radius.
		//
		// Testing against the enemy's centre alone means a small projectile has to pass within
		// its own width of that centre - while the bug's visible body is 28 to 85 units
		// across. Pellets that visibly strike the body sail through doing nothing, which reads
		// as "I hit it and it did not die". Enemies are not points; they are the size they are
		// drawn.
		const UKBEnemyArchetype* Archetype =
			Archetypes.IsValidIndex(Sim[Index].ArchetypeIndex) ? Archetypes[Sim[Index].ArchetypeIndex].Get() : nullptr;
		const float BodyRadius = Archetype ? Archetype->BodyRadius : 0.f;
		const float EffectiveRadius = Radius + BodyRadius;

		const FVector ClosestPoint = Start + Segment * Along;
		if (FVector::DistSquared2D(ClosestPoint, Sim[Index].Location) > EffectiveRadius * EffectiveRadius)
		{
			continue;
		}

		// Hit the nearest bug along the ray, not merely the nearest to it.
		if (Along < BestAlong)
		{
			BestAlong = Along;
			BestIndex = Index;
		}
	}

	if (BestIndex == INDEX_NONE)
	{
		return false;
	}

	if (OutHitLocation)
	{
		// The bug's own position, not the closest point on the ray: an impact effect should
		// sit on the body it struck, not float in the air beside it.
		*OutHitLocation = Sim[BestIndex].Location;
	}

	ApplyDamageToEnemy(BestIndex, Damage, Killer);
	return true;
}

