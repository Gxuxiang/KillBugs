bool AKBEnemyDirector::ApplyDamageToEnemy(int32 SimIndex, float Damage, AKBPlayerState* Killer)
{
	if (!HasAuthority() || Damage <= 0.f || !Sim.IsValidIndex(SimIndex))
	{
		return false;
	}

	FKBEnemySim& Enemy = Sim[SimIndex];

	// Phase scaling: the same shot hurts far more during Explore than during a wave.
	Enemy.Health -= Damage * EnemyDamageTakenScale;

	const UWorld* World = GetWorld();
	Enemy.HitFlashEndTime = (World ? World->GetTimeSeconds() : 0.f) + 0.08f;

	if (Enemy.Health > 0.f)
	{
		return false;
	}

	// Read everything that describes this death BEFORE the entry goes: `Enemy` is a reference
	// into Sim, so it dangles the moment RemoveAt runs, and the archetype is only resolvable
	// while the entry still exists. Both the reward and the drop need them, so they are hoisted
	// here rather than resolved inside the reward's guard - a kill credited to nobody still has
	// no killer, but it does still have an archetype and a place to fall.
	const FVector DeathLocation = Enemy.Location;
	const UKBEnemyArchetype* Archetype =
		Archetypes.IsValidIndex(Enemy.ArchetypeIndex) ? Archetypes[Enemy.ArchetypeIndex].Get() : nullptr;

	if (IsValid(Killer) && Archetype)
	{
		// The killer's own XP multiplier, not the archetype's raw value.
		//
		// This multiplier was already folded into the stat sheet and exposed as
		// GetXpMultiplier(), but nothing ever called it - so the card that grants +15% XP
		// was a card that did nothing at all. Read at the moment of the kill rather than
		// cached, for the same reason weapons read the damage multiplier at fire time: a
		// card picked mid-run should change the very next kill.
		float XpMultiplier = 1.f;
		if (const APawn* KillerPawn = Killer->GetPawn())
		{
			if (const UKBStatSheetComponent* KillerStats =
				KillerPawn->FindComponentByClass<UKBStatSheetComponent>())
			{
				XpMultiplier = KillerStats->GetXpMultiplier();
			}
		}

		Killer->AddXP(FMath::RoundToInt(Archetype->XpValue * XpMultiplier));
		Killer->AddGold(Archetype->GoldValue);
	}

	// Loot is a property of the bug dying, not a reward for killing it - see RollDropForDeath.
	// Rolled for every death, credited or not.
	if (Archetype && LootDirector.IsValid())
	{
		LootDirector->RollDropForDeath(DeathLocation, *Archetype);
	}

	// Death is a removal from both arrays. Removing at the same index preserves the
	// index-parallel invariant, and on clients the visualizer drops the instance when the
	// entry stops appearing.
	Sim.RemoveAt(SimIndex);
	if (ReplicatedEnemies.Items.IsValidIndex(SimIndex))
	{
		ReplicatedEnemies.Items.RemoveAt(SimIndex);
	}
	ReplicatedEnemies.MarkArrayDirty();

	return true;
}

void AKBEnemyDirector::TickContactDamage(float DeltaSeconds)
{
	// Its own cadence rather than per frame: biting is a rate, and applying it every frame
	// would make damage scale with frame rate.
	ContactDamageAccumulator += DeltaSeconds;
	if (ContactDamageAccumulator < KBSettings().ContactDamageInterval)
	{
		return;
	}
	ContactDamageAccumulator = 0.f;

	const UWorld* World = GetWorld();
	if (!World || Sim.Num() == 0)
	{
		return;
	}

	// The widest reach any archetype can have, for the broad phase below. Computed once per
	// cadence rather than per player, and per archetype rather than per bug.
	float MaxBodyRadius = 0.f;
	for (const TObjectPtr<UKBEnemyArchetype>& Archetype : Archetypes)
	{
		if (Archetype)
		{
			MaxBodyRadius = FMath::Max(MaxBodyRadius, Archetype->BodyRadius);
		}
	}

	for (FConstPlayerControllerIterator It = World->GetPlayerControllerIterator(); It; ++It)
	{
		APlayerController* PlayerController = It->Get();
		APawn* Pawn = PlayerController ? PlayerController->GetPawn() : nullptr;
		if (!IsValid(Pawn))
		{
			continue;
		}

		if (const AKBPlayerState* PlayerState = PlayerController->GetPlayerState<AKBPlayerState>())
		{
			if (PlayerState->IsDowned())
			{
				continue; // already out; do not keep chewing a corpse
			}
		}

		UKBStatSheetComponent* Stats = Pawn->FindComponentByClass<UKBStatSheetComponent>();
		if (!Stats)
		{
			continue;
		}

		// Contact is measured EDGE TO EDGE, and the bug's edge is its BodyRadius - the same number
		// that already drives separation, weapon hit tests and the blob shadow, and the number the
		// mesh is scaled to match.
		//
		// A single centre-to-centre radius cannot be right for both ends of the size range. At the
		// old fixed 110 from the player's centre, a Runner (BodyRadius 28) started biting with
		// ~48 units of visible empty space between the two bodies, while a Brute (85) had to be
		// overlapping the player before it counted - so small bugs bit from thin air and the big
		// one never seemed to reach. Both are the same bug: the test ignored the model.
		const float PlayerRadius = Pawn->GetSimpleCollisionRadius();

		// Broad phase at the widest reach, so the grid never culls a bug the exact test would keep.
		//
		// Reset first: this array is a member scratch buffer, and QuerySphere only APPENDS. Without
		// the reset it accumulates across players and across frames, and once any bug dies the
		// older, longer indices point past the end of Sim and the bounds check fires.
		ContactScratch.Reset();
		Grid.QuerySphere(Pawn->GetActorLocation(), PlayerRadius + MaxBodyRadius + KBSettings().ContactGap,
			INDEX_NONE, Sim, ContactScratch);
		if (ContactScratch.Num() == 0)
		{
			continue;
		}

		float Damage = 0.f;
		int32 Biters = 0;
		for (const int32 Index : ContactScratch)
		{
			if (Biters >= KBSettings().MaxSimultaneousContacts)
			{
				break;
			}

			const UKBEnemyArchetype* Archetype =
				Archetypes.IsValidIndex(Sim[Index].ArchetypeIndex) ? Archetypes[Sim[Index].ArchetypeIndex].Get() : nullptr;
			if (!Archetype)
			{
				continue;
			}

			// Narrow phase: this bug's own reach, not the widest one.
			const float Reach = PlayerRadius + Archetype->BodyRadius + KBSettings().ContactGap;
			if (FVector::DistSquared2D(Pawn->GetActorLocation(), Sim[Index].Location) > Reach * Reach)
			{
				continue;
			}

			Damage += Archetype->GetContactDamageForWave(CurrentWaveIndex);
			++Biters;
		}

		if (Biters > 0)
		{
			Stats->ApplyDamage(Damage);
		}
	}
}

